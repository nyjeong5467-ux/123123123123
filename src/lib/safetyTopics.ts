/** 질문 문장에서 주제를 고른다(낱말이 많이·앞쪽에 맞을수록 높은 점수). 없으면 null */
export function matchTopic(q: string): SafetyTopic | null {
  let best: SafetyTopic | null = null
  let bestScore = 0
  for (const t of SAFETY_TOPICS) {
    let score = 0
    t.words.forEach((w, i) => { if (q.includes(w)) score += 10 - Math.min(i, 8) })
    if (score > bestScore) { best = t; bestScore = score }
  }
  return best
}
